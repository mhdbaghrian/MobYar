function createMudaafMujarrad(
  root: string,
  ainMadi: 'َ' | 'ِ' | 'ُ',
  ainMudari: 'َ' | 'ِ' | 'ُ',
  meaningBase: string,
  persianPrefix: string,
  persianMadi: string,
  persianMudari: string,
  masdar?: string,
  quranicAyah?: string
): VerbConjugation {
  const forms = generateMudaafMujarrad(root, ainMadi, ainMudari);
  let babId: any = 'mujarrad_nasara';
  if (ainMadi === 'َ' && ainMudari === 'ُ') babId = 'mujarrad_nasara';
  else if (ainMadi === 'َ' && ainMudari === 'ِ') babId = 'mujarrad_daraba';
  else if (ainMadi === 'َ' && ainMudari === 'َ') babId = 'mujarrad_fataha';
  else if (ainMadi === 'ِ' && ainMudari === 'َ') babId = 'mujarrad_alima';
  else if (ainMadi === 'ُ' && ainMudari === 'ُ') babId = 'mujarrad_hasuna';
  else if (ainMadi === 'ِ' && ainMudari === 'ِ') babId = 'mujarrad_hasiba';

  const isTransitive = babId !== 'mujarrad_hasuna';
  const nafyMadi = generateNafyMadi(forms.madi);
  const nafyMudari = generateNafyMudari(forms.mudari);
  const madiMajhul = isTransitive ? forms.madiMajhul : undefined;
  const mudariMajhul = isTransitive ? forms.mudariMajhul : undefined;
  const nafyMadiMajhul = madiMajhul ? generateNafyMadiMajhul(madiMajhul) : undefined;
  const nafyMudariMajhul = mudariMajhul ? generateNafyMudariMajhul(mudariMajhul) : undefined;
  const nahyMajhul = mudariMajhul ? generateNahyMajhul(mudariMajhul) : undefined;

  return {
    root,
    babId,
    meaningBase,
    masdar,
    verbType: 'mudaaf',
    isTransitive,
    quranicAyah,
    persianStem: { prefix: persianPrefix, stemMadi: persianMadi, stemMudari: persianMudari },
    madi: forms.madi,
    mudari: forms.mudari,
    amr: forms.amr,
    nahy: forms.nahy,
    nahyMajhul,
    madiMajhul,
    mudariMajhul,
    nafyMadi,
    nafyMudari,
    nafyMadiMajhul,
    nafyMudariMajhul,
  };
}

function createMudaafAugmented(
  root: string,
  babId: any,
  meaningBase: string,
  persianPrefix: string,
  persianMadi: string,
  persianMudari: string,
  masdar?: string,
  quranicAyah?: string
): VerbConjugation {
  const forms = generateMudaafAugmented(root, babId);
  if (!forms) throw new Error(`Failed to generate mudaaf augmented forms for ${root} in ${babId}`);

  const isTransitive = babId !== "infi'al" && babId !== "if'ilal" && babId !== "tafa'ul";
  const nafyMadi = generateNafyMadi(forms.madi);
  const nafyMudari = generateNafyMudari(forms.mudari);
  const madiMajhul = forms.madiMajhul;
  const mudariMajhul = forms.mudariMajhul;
  const nahyMajhul = mudariMajhul ? generateNahyMajhul(mudariMajhul) : undefined;
  const nafyMadiMajhul = madiMajhul ? generateNafyMadiMajhul(madiMajhul) : undefined;
  const nafyMudariMajhul = mudariMajhul ? generateNafyMudariMajhul(mudariMajhul) : undefined;

  return {
    root,
    babId,
    meaningBase,
    masdar,
    verbType: 'mudaaf',
    isTransitive,
    quranicAyah,
    persianStem: { prefix: persianPrefix, stemMadi: persianMadi, stemMudari: persianMudari },
    madi: forms.madi,
    mudari: forms.mudari,
    amr: forms.amr,
    nahy: forms.nahy,
    nahyMajhul,
    madiMajhul,
    mudariMajhul,
    nafyMadi,
    nafyMudari,
    nafyMadiMajhul,
    nafyMudariMajhul,
  };
}

function createSoundMujarrad(
  root: string,
  ainMadi: 'َ' | 'ِ' | 'ُ',
  ainMudari: 'َ' | 'ِ' | 'ُ',
  meaningBase: string,
  persianPrefix: string,
  persianMadi: string,
  persianMudari: string,
  masdar?: string,
  quranicAyah?: string
): VerbConjugation {
  const [f, a, l] = root.split(' ');
  const forms = generateSoundConjugation(f, a, l, ainMadi, ainMudari);
  let babId: any = 'mujarrad';
  if (ainMadi === 'َ' && ainMudari === 'ُ') babId = 'mujarrad_nasara';
  else if (ainMadi === 'َ' && ainMudari === 'ِ') babId = 'mujarrad_daraba';
  else if (ainMadi === 'َ' && ainMudari === 'َ') babId = 'mujarrad_fataha';
  else if (ainMadi === 'ِ' && ainMudari === 'َ') babId = 'mujarrad_alima';
  else if (ainMadi === 'ُ' && ainMudari === 'ُ') babId = 'mujarrad_hasuna';
  else if (ainMadi === 'ِ' && ainMudari === 'ِ') babId = 'mujarrad_hasiba';

  const isTransitive = babId !== 'mujarrad_hasuna';
  const nahy = generateNahy(forms.mudari);
  const amr = generateAmr(forms.madi, forms.mudari, babId, root, ainMudari);
  const madiMajhul = isTransitive ? generateMadiMajhul(root, babId) || undefined : undefined;
  const mudariMajhul = isTransitive ? generateMudariMajhul(root, babId) || undefined : undefined;
  const nahyMajhul = mudariMajhul ? generateNahyMajhul(mudariMajhul) : undefined;
  const nafyMadi = generateNafyMadi(forms.madi);
  const nafyMudari = generateNafyMudari(forms.mudari);
  const nafyMadiMajhul = madiMajhul ? generateNafyMadiMajhul(madiMajhul) : undefined;
  const nafyMudariMajhul = mudariMajhul ? generateNafyMudariMajhul(mudariMajhul) : undefined;

  return {
    root,
    babId,
    meaningBase,
    masdar,
    verbType: 'salim',
    isTransitive,
    quranicAyah,
    persianStem: { prefix: persianPrefix, stemMadi: persianMadi, stemMudari: persianMudari },
    madi: forms.madi,
    mudari: forms.mudari,
    amr,
    nahy,
    nahyMajhul,
    madiMajhul,
    mudariMajhul,
    nafyMadi,
    nafyMudari,
    nafyMadiMajhul,
    nafyMudariMajhul,
  };
}

function createAugmented(
  root: string,
  babId: any,
  meaningBase: string,
  persianPrefix: string,
  persianMadi: string,
  persianMudari: string,
  masdar?: string,
  quranicAyah?: string,
  verbType: 'salim' | 'mudaaf' = 'salim'
): VerbConjugation {
  const forms = generateAugmentedConjugation(root, babId);
  if (!forms) {
    throw new Error(`Failed to generate augmented forms for ${root} in ${babId}`);
  }

  const isTransitive = babId !== "infi'al" && babId !== "tafa'lul";
  const nahy = generateNahy(forms.mudari);
  const amr = generateAmr(forms.madi, forms.mudari, babId, root);
  const madiMajhul = isTransitive ? generateMadiMajhul(root, babId) || undefined : undefined;
  const mudariMajhul = isTransitive ? generateMudariMajhul(root, babId) || undefined : undefined;
  const nahyMajhul = mudariMajhul ? generateNahyMajhul(mudariMajhul) : undefined;
  const nafyMadi = generateNafyMadi(forms.madi);
  const nafyMudari = generateNafyMudari(forms.mudari);
  const nafyMadiMajhul = madiMajhul ? generateNafyMadiMajhul(madiMajhul) : undefined;
  const nafyMudariMajhul = mudariMajhul ? generateNafyMudariMajhul(mudariMajhul) : undefined;

  return {
    root,
    babId,
    meaningBase,
    masdar,
    verbType,
    isTransitive,
    quranicAyah,
    persianStem: { prefix: persianPrefix, stemMadi: persianMadi, stemMudari: persianMudari },
    madi: forms.madi,
    mudari: forms.mudari,
    amr,
    nahy,
    nahyMajhul,
    madiMajhul,
    mudariMajhul,
    nafyMadi,
    nafyMudari,
    nafyMadiMajhul,
    nafyMudariMajhul,
  };
}

