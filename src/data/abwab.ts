// Export comprehensive verb library as VERB_LIBRARY
export const VERB_LIBRARY: VerbConjugation[] = COMPREHENSIVE_VERB_LIBRARY;

export function getBabById(id: BabId): BabInfo {
  const found = ABWAB_LIST.find((b) => b.id === id);
  if (!found) throw new Error(`Bab with id ${id} not found`);
  return found;
}

export function getSeeghehByIndex(index: number): SeeghehInfo {
  const found = SEEGHEHS.find((s) => s.index === index);
  if (!found) throw new Error(`Seegheh with index ${index} not found`);
  return found;
}

export function getVerbsByBab(babId: BabId): VerbConjugation[] {
  if (babId === 'mujarrad') {
    return VERB_LIBRARY.filter((v) => v.babId.startsWith('mujarrad'));
  }
  return VERB_LIBRARY.filter((v) => v.babId === babId);
}

export function searchVerbs(query: string): VerbConjugation[] {
  const q = query.trim().toLowerCase();
  if (!q) return VERB_LIBRARY;
  return VERB_LIBRARY.filter((v) => {
    return (
      v.root.toLowerCase().includes(q) ||
      v.root.replace(/\s+/g, '').includes(q.replace(/\s+/g, '')) ||
      v.meaningBase.toLowerCase().includes(q) ||
      v.madi[0].includes(q) ||
      v.mudari[0].includes(q)
    );
  });
}
